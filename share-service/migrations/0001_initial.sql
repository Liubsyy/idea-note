PRAGMA foreign_keys = ON;
CREATE TABLE IF NOT EXISTS publishers (
 id TEXT PRIMARY KEY, name TEXT NOT NULL, token_hash TEXT NOT NULL UNIQUE,
 enabled INTEGER NOT NULL DEFAULT 1, expires_at INTEGER,
 max_shares INTEGER NOT NULL DEFAULT 100, max_bytes INTEGER NOT NULL DEFAULT 1073741824,
 created_at INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS shares (
 id TEXT PRIMARY KEY, owner TEXT NOT NULL REFERENCES publishers(id), title TEXT NOT NULL,
 status TEXT NOT NULL, version INTEGER NOT NULL, stage_id TEXT NOT NULL,
 doc_key TEXT NOT NULL, bytes INTEGER NOT NULL, expires_at INTEGER,
 created_at INTEGER NOT NULL, updated_at INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS shares_owner ON shares(owner);
CREATE TABLE IF NOT EXISTS stages (
 id TEXT PRIMARY KEY, owner TEXT NOT NULL REFERENCES publishers(id), share_id TEXT NOT NULL,
 base_version INTEGER NOT NULL, state TEXT NOT NULL DEFAULT 'open', created_at INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS assets (
 id TEXT PRIMARY KEY, stage_id TEXT NOT NULL REFERENCES stages(id), name TEXT NOT NULL,
 mime TEXT NOT NULL, bytes INTEGER NOT NULL, object_key TEXT NOT NULL UNIQUE, created_at INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS assets_stage ON assets(stage_id);
CREATE TABLE IF NOT EXISTS settings (id INTEGER PRIMARY KEY CHECK(id=1), json TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS sessions (token_hash TEXT PRIMARY KEY, expires_at INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS attempts (id TEXT PRIMARY KEY, hits INTEGER NOT NULL, reset_at INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS audit (id TEXT PRIMARY KEY, actor TEXT NOT NULL, action TEXT NOT NULL, target TEXT, at INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS audit_at ON audit(at);

CREATE TABLE IF NOT EXISTS restore_guard (id INTEGER PRIMARY KEY CHECK(id=1));
CREATE TRIGGER IF NOT EXISTS restore_requires_empty BEFORE INSERT ON restore_guard
WHEN EXISTS(SELECT 1 FROM publishers) OR EXISTS(SELECT 1 FROM shares)
BEGIN SELECT RAISE(ABORT, 'Restore requires an empty instance'); END;
CREATE TABLE IF NOT EXISTS restore_jobs (id TEXT PRIMARY KEY CHECK(id='active'), token TEXT NOT NULL, created_at INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS restore_objects (job TEXT NOT NULL, object_key TEXT NOT NULL, PRIMARY KEY(job,object_key));
